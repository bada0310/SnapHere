물리 삭제를 도입할 때는 이 외래키가 막는다 — 방문 사실을 지우려면 먼저 다른 근거로 옮겨야 한다';

-- 내 방문 기록 최신순 커서 페이징 (VST-003). uk_visits_daily 는 (user_id, place_id) 로 시작해
-- 날짜 정렬에 쓸 수 없다.
create index idx_visits_user_recent on visits (user_id, visited_on desc, visit_id desc);

-- 장소 방문자 목록 (VST-005).
create index idx_visits_place on visits (place_id, visited_on desc, visit_id desc);
