-- SnapHere V15 — 방문 기록(발자국)
-- 요구사항: VST-001, VST-002, VST-003, VST-004, VST-005, PST-039
-- 설계: 요구사항·기능 명세 v1.1.4 > 6. 데이터 설계 > visits

create table visits (
    visit_id   bigint      generated by default as identity primary key,
    user_id    uuid        not null,
    place_id   bigint      not null,
    post_id    bigint      not null,
    visited_on date        not null,
    created_at timestamptz not null default now(),

    -- 같은 날 같은 장소는 한 번만 기록한다 (VST-002). 애플리케이션에서 조회 후 삽입하면
    -- 같은 사람이 연달아 올릴 때 두 건이 들어가므로 판정을 DB 에 맡긴다.
    constraint uk_visits_daily unique (user_id, place_id, visited_on),
    constraint fk_visits_user  foreign key (user_id)  references users (id) on delete cascade,
    constraint fk_visits_place foreign key (place_id) references places (place_id),
    constraint fk_visits_post  foreign key (post_id)  references posts (post_id)
);

